CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL,
    phone VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_customers_email UNIQUE (email),
    CONSTRAINT ck_customers_name_not_blank CHECK (length(trim(full_name)) > 0)
);
CREATE UNIQUE INDEX ux_customers_email_lower ON customers (lower(email));

CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number VARCHAR(12) NOT NULL,
    room_type VARCHAR(20) NOT NULL,
    capacity INTEGER NOT NULL,
    price_per_night NUMERIC(10, 2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_rooms_number UNIQUE (number),
    CONSTRAINT ck_rooms_type CHECK (room_type IN ('SINGLE', 'DOUBLE', 'DELUXE', 'SUITE')),
    CONSTRAINT ck_rooms_capacity CHECK (capacity > 0),
    CONSTRAINT ck_rooms_price CHECK (price_per_night > 0),
    CONSTRAINT ck_rooms_status CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'CLEANING', 'MAINTENANCE'))
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL,
    guests INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'BOOKED',
    total_price NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_bookings_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT,
    CONSTRAINT fk_bookings_room FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE RESTRICT,
    CONSTRAINT ck_bookings_dates CHECK (check_out_date > check_in_date),
    CONSTRAINT ck_bookings_guests CHECK (guests > 0),
    CONSTRAINT ck_bookings_status CHECK (status IN ('BOOKED', 'CONFIRMED', 'CHECKED_IN', 'CHECKED_OUT', 'CANCELLED')),
    CONSTRAINT ck_bookings_total_price CHECK (total_price >= 0)
);
CREATE INDEX ix_bookings_room_dates ON bookings (room_id, check_in_date, check_out_date);
CREATE INDEX ix_bookings_customer ON bookings (customer_id);
